// Rewrites the coverage summary and the "No source for" lines in docs/DATA_AUDIT.md
// from src/data/pyramids.json, so the report cannot drift from the data.
// Run: node scripts/audit-coverage.mjs [--check]
import { readFileSync, writeFileSync } from 'node:fs';

const root = new URL('../', import.meta.url);
const pyramids = JSON.parse(readFileSync(new URL('src/data/pyramids.json', root), 'utf8'));
const auditUrl = new URL('docs/DATA_AUDIT.md', root);
const audit = readFileSync(auditUrl, 'utf8');

const START = '<!-- coverage:start -->';
const END = '<!-- coverage:end -->';

const fieldCounts = new Map();
for (const p of pyramids) {
  for (const f of p.campi_senza_fonte ?? []) fieldCounts.set(f, (fieldCounts.get(f) ?? 0) + 1);
}
const status = (s) => pyramids.filter((p) => p.stato_verifica === s).length;
const withGaps = pyramids.filter((p) => (p.campi_senza_fonte ?? []).length > 0).length;
const totalGaps = [...fieldCounts.values()].reduce((a, b) => a + b, 0);

const rows = [...fieldCounts.entries()]
  .sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0]))
  .map(([f, n]) => `| \`${f}\` | ${n} |`);

const summary = [
  START,
  '## Coverage report',
  '',
  'Generated by `node scripts/audit-coverage.mjs` from `src/data/pyramids.json`.',
  '',
  `- Sites: ${pyramids.length}. Verified ${status('verified')}, partly sourced ${status('partial')}, unverified ${status('unverified')}.`,
  `- Sites with at least one unsourced field: ${withGaps}. Unsourced fields in total: ${totalGaps}.`,
  '',
  '| Field without a source | Sites |',
  '|---|---|',
  ...rows,
  END,
].join('\n');

let out;
if (audit.includes(START)) {
  out = audit.replace(new RegExp(`${START}[\\s\\S]*?${END}`), summary);
} else {
  out = audit.replace('\n## Coordinate check', `\n${summary}\n\n## Coordinate check`);
}

// Per-site lines: replace, add or drop "- No source for:" under each "### `id`" heading.
const byId = new Map(pyramids.map((p) => [p.id, p]));
const lines = out.split('\n');
const result = [];
for (let i = 0; i < lines.length; i++) {
  const line = lines[i];
  const m = line.match(/^### `([^`]+)`/);
  if (m && byId.has(m[1])) {
    result.push(line);
    const gaps = byId.get(m[1]).campi_senza_fonte ?? [];
    if (lines[i + 1]?.startsWith('- No source for:')) i++;
    if (gaps.length) result.push(`- No source for: ${gaps.join(', ')}`);
    continue;
  }
  result.push(line);
}
out = result.join('\n');

if (process.argv.includes('--check')) {
  if (out !== audit) {
    console.error('docs/DATA_AUDIT.md is out of date: run node scripts/audit-coverage.mjs');
    process.exit(1);
  }
  console.log('DATA_AUDIT.md coverage is up to date.');
} else {
  writeFileSync(auditUrl, out);
  console.log(`Coverage: ${withGaps} sites with gaps, ${totalGaps} unsourced fields.`);
}
